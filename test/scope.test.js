"use strict";
// Le microscope (src/scope.js) : le flacon garde l'eau du jour, la goutte se lit sans chiffre, le rythme suit l'heure D'ni.
const assert = require("assert");
const S = require("../src/scope");
let n = 0; const ok = (c, m) => { assert(c, m); n++; };
const T = Date.UTC(2026, 9, 24, 12), D = S.DAY;
ok(S.paramsOf(null).dry && S.paramsOf({}).dry, "pas de flacon : une lame sèche");
const cv = { colonies: 0, fedAt: 0 };
ok(S.paramsOf(S.sample(cv, T)).cells === 0 && !S.paramsOf(cv.flask).dry, "un lac sans colonie : une goutte vide");
cv.colonies = 3; cv.fedAt = T - D / 2; S.logFeed(cv, T - D / 2);
let p = S.paramsOf(S.sample(cv, T));
ok(p.cells > 0 && p.cells < 10 && p.fresh === 1 && p.divide > 0 && !p.dormant && !p.burst, "trois colonies nourries ce matin : quelques cellules vives qui se divisent");
cv.colonies = 200; p = S.paramsOf(S.sample(cv, T));
ok(p.cells === 90, "deux cents colonies : le champ grouille (90 cellules au plus)");
cv.colonies = 30; cv.fedAt = T - 7 * D; p = S.paramsOf(S.sample(cv, T));
ok(p.fresh === 0 && p.dormant && p.divide === 0, "oubliées depuis une semaine : des braises");
cv.fedAt = T - 3.5 * D; p = S.paramsOf(S.sample(cv, T));
ok(p.fresh > 0.4 && p.fresh < 0.6 && !p.dormant, "nourries il y a trois jours et demi : entre les deux");
for (let i = 0; i < 3; i++) S.logFeed(cv, T - 3600000 * (i + 1));
cv.fedAt = T - 3600000; p = S.paramsOf(S.sample(cv, T));
ok(p.burst && p.divide === 0, "trois ambrés en une journée : elles crèvent en rafale");
p = S.paramsOf(S.sample(cv, T + 2 * D));
ok(!p.burst, "deux jours plus tard, la rafale est passée");
ok(cv.flask.at === T + 2 * D, "le flacon garde l'instant où on l'a rempli");
for (let i = 0; i < 20; i++) S.logFeed(cv, T + i);
ok(cv.feeds.length === 12, "on garde douze repas");
const rs = []; for (let h = 0; h < 31; h += 0.25) rs.push(S.rhythm(T + h * 3600000));
ok(Math.max(...rs) > 0.95 && Math.min(...rs) < 0.05, "le rythme D'ni monte et retombe");
const peaks = rs.filter((v, i) => i > 0 && i < rs.length - 1 && v > rs[i - 1] && v >= rs[i + 1] && v > 0.5).length;
ok(peaks >= 4 && peaks <= 6, "cinq pics par yahr, à peu près : " + peaks);
console.log(`scope.test.js ok (${n} vérifications)`);
