function makeT(getLang) {
  return (key, p) => {
    const l = (getLang && getLang()) || "en";
    let s = (D[l] && D[l][key]) || D.en[key] || key;
    if (p) s = s.replace(/\{(\w+)\}/g, (m, k) => (p[k] == null ? m : String(p[k])));
    return s;
  };
}
module.exports = { makeT, D };
